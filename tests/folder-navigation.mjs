import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
const script=html.match(/<script>([\s\S]*?)<\/script>/)[1];
const helper=script.slice(script.indexOf('function folderCompanyCount('),script.indexOf('function opportunityDataset('));
const state={userId:'account',authUserId:'member',readOnly:false,oppFilters:{folderId:'f1',archive:'ativas'},folders:Array.from({length:40},(_,i)=>({id:'f'+i,nome:i===1?'Guindastes':'Pasta '+i,cor:'#10a37f'})),companies:[]};
const saved=new Map();
const scope=vm.createContext({state,localStorage:{getItem:k=>saved.get(k)||null,setItem:(k,v)=>saved.set(k,v)},document:{addEventListener(){}},esc:value=>String(value||'').replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('"','&quot;'),activeCompanies:()=>state.companies,icon:()=>''});
Object.assign(scope,{companyListScope:()=>'oportunidades',companyListFilters:()=>state.oppFilters,companyListBase:()=>state.companies});
vm.runInContext(helper,scope);
const picker=scope.renderFolderPicker(state.folders[1]);
assert.ok(picker.includes('id="folderMenuSearch"'));assert.ok(picker.includes('Guindastes'));
assert.equal((picker.match(/data-folder-view=/g)||[]).length,40);
assert.ok(picker.includes('id="oppFolderManager"'));assert.ok(picker.includes('data-rename-folder'));
assert.ok(!scope.renderOpportunityEmpty().includes('Criar radar'));
assert.ok(scope.renderOpportunityEmpty().includes('Esta pasta ainda não tem empresas'));
state.companies=[{id:'c1',folderIds:['f1']}];
assert.ok(scope.renderOpportunityEmpty().includes('Nenhuma oportunidade encontrada'));
state.readOnly=true;const readOnly=scope.renderFolderPicker(state.folders[1]);
assert.ok(!readOnly.includes('id="newOppFolder"'));assert.ok(!readOnly.includes('data-delete-folder'));assert.ok(!readOnly.includes('data-rename-folder'));
assert.equal(scope.folderSearchKey('Locação'),'locacao');
saved.set('leadscope_folder_favorites_member',JSON.stringify(['f10','deleted']));
assert.deepEqual(Array.from(scope.folderFavorites()),['f10']);
assert.ok(scope.renderFolderPicker(null).indexOf('data-folder-view="f10"')<scope.renderFolderPicker(null).indexOf('data-folder-view="f0"'));
const chipStart=script.indexOf('function opportunityFilterChips('),chipEnd=script.indexOf('function renderOportunidades(',chipStart);
vm.runInContext(script.slice(chipStart,chipEnd),vm.createContext({}));
assert.ok(html.includes('.folder-menu-row[hidden]{display:none;}'));
console.log('Folder navigation: large lists, favorites, accent-insensitive search, empty states and read-only controls passed. No database changes.');
